import { createServer } from 'node:http';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { build } from 'esbuild';
import { chromium } from 'playwright';

const [inter400, inter600, geistMono400] = process.argv.slice(2);
if (!inter400 || !inter600 || !geistMono400) {
  throw new Error('Usage: node scripts/generate-uikit-fonts.mjs INTER_400.ttf INTER_600.ttf GEIST_MONO_400.ttf');
}

const root = process.cwd();
const temporaryBundle = '/tmp/codeai-uikit-font-generator.js';
await build({
  entryPoints: [resolve(root, 'scripts/generate-uikit-fonts-browser.ts')],
  outfile: temporaryBundle,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
});
const assets = new Map([
  ['/generator.js', temporaryBundle],
  ['/Inter-Regular.ttf', resolve(inter400)],
  ['/Inter-SemiBold.ttf', resolve(inter600)],
  ['/GeistMono-Regular.ttf', resolve(geistMono400)],
]);
const server = createServer(async (request, response) => {
  if (request.url === '/') {
    response.setHeader('content-type', 'text/html');
    response.end('<script type="module" src="/generator.js"></script>');
    return;
  }
  const path = assets.get(request.url || '');
  if (!path) { response.statusCode = 404; response.end(); return; }
  response.setHeader('content-type', request.url?.endsWith('.js') ? 'text/javascript' : 'application/octet-stream');
  response.end(await readFile(path));
});
await new Promise((accept) => server.listen(0, '127.0.0.1', accept));
const address = server.address();
if (!address || typeof address === 'string') throw new Error('Font generator server did not start.');

const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
try {
  const page = await browser.newPage();
  page.on('console', (message) => process.stdout.write(`${message.text()}\n`));
  await page.goto(`http://127.0.0.1:${address.port}`);
  await page.waitForFunction(() => typeof window.generateCodeAiUikitFonts === 'function');
  const generated = await page.evaluate(() => window.generateCodeAiUikitFonts());
  const unwrap = (family) => Object.values(Object.values(family)[0])[0];
  const fonts = {
    inter: { 400: unwrap(generated.inter400), 600: unwrap(generated.inter600) },
    geistMono: { 400: unwrap(generated.geistMono400) },
  };
  const details = Object.entries(fonts).flatMap(([family, weights]) => Object.entries(weights).map(([weight, data]) => ({
    family, weight, glyphs: data.chars.length, pages: data.pages.length,
    width: data.common.scaleW, height: data.common.scaleH,
    encodedBytes: Math.floor((data.pages[0].length - data.pages[0].indexOf(',') - 1) * 3 / 4),
  })));
  const output = `/* Generated by scripts/generate-uikit-fonts.mjs. Inter and Geist are SIL Open Font License 1.1. */\n`
    + `export const codeAiUikitFonts = ${JSON.stringify(fonts)};\n`
    + `export const codeAiUikitFontMetrics = ${JSON.stringify(details, null, 2)} as const;\n`;
  await writeFile(resolve(root, 'src/features/shell/immersive/uikitFonts.generated.ts'), output);
  process.stdout.write(`${JSON.stringify(details, null, 2)}\n`);
} finally {
  await browser.close();
  server.close();
}
